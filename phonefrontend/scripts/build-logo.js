// Builds src/assets/logo.js from the website's logo (frontend/src/assets/strauss-logo.svg), for SvgXml.
// The source is an Inkscape file: it has no viewBox (so it would not scale to its box and is cut off)
// and Inkscape/Sodipodi metadata that React warns about. Run again if the website's logo changes:
//   node scripts/build-logo.js
const fs = require('fs')
const path = require('path')

const source = path.join(__dirname, '..', '..', 'frontend', 'src', 'assets', 'strauss-logo.svg')
const target = path.join(__dirname, '..', 'src', 'assets', 'logo.js')

let svg = fs.readFileSync(source, 'utf8')
svg = svg
  .replace(/<\?xml[^>]*\?>/, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
  .replace(/<(inkscape|sodipodi):[\w-]+[^>]*?\/>/g, '') // Inkscape-only elements: perspective, namedview
  .replace(/\s(xmlns|inkscape|sodipodi):[\w-]+="[^"]*"/g, '')

// the size becomes the viewBox, so the drawing scales to whatever box shows it
const open = svg.match(/<svg[^>]*>/)[0]
const width = open.match(/\swidth="([\d.]+)"/)[1]
const height = open.match(/\sheight="([\d.]+)"/)[1]
const cleanOpen = open
  .replace(/\s(width|height|id|version)="[^"]*"/g, '')
  .replace('<svg', `<svg viewBox="0 0 ${width} ${height}"`)
svg = svg.replace(open, cleanOpen).replace(/\n\s*\n/g, '\n').trim()

fs.writeFileSync(target, `// generated by scripts/build-logo.js from frontend/src/assets/strauss-logo.svg (shown with SvgXml)\nexport default ${JSON.stringify(svg)}\n`)
console.log(`logo.js: ${svg.length} characters, viewBox 0 0 ${width} ${height}`)
